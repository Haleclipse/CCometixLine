#!/usr/bin/env node
// Regenerates assets/nerd-glyphs.txt, the icon browser's table, from Nerd
// Fonts' glyphnames.json at a release tag.
//
//   node scripts/nerd-glyphs.mjs [version]     (default: the one below)
//
// Behind a proxy, set NODE_USE_ENV_PROXY=1 so fetch takes HTTPS_PROXY.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const VERSION = process.argv[2] ?? '3.5.1'
const url = `https://raw.githubusercontent.com/ryanoasis/nerd-fonts/v${VERSION}/glyphnames.json`
const out = fileURLToPath(new URL('../assets/nerd-glyphs.txt', import.meta.url))

const res = await fetch(url)
if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
const { METADATA: meta, ...glyphs } = await res.json()
if (meta?.version !== VERSION) throw new Error(`asked for ${VERSION}, got ${meta?.version}`)

// One line per codepoint with every name it has; the classes with the most
// glyphs first, which is also the order an empty search lists them in.
const byCode = new Map()
for (const [name, { code }] of Object.entries(glyphs)) {
  if (!/^[a-z0-9_-]+$/.test(name) || !/^[0-9a-f]{4,6}$/.test(code)) {
    throw new Error(`unexpected entry ${name}: ${code}`)
  }
  byCode.set(code, [...(byCode.get(code) ?? []), name])
}
const classOf = (name) => name.split('-')[0]
const size = new Map()
for (const name of Object.keys(glyphs)) size.set(classOf(name), (size.get(classOf(name)) ?? 0) + 1)
const rank = (name) => -size.get(classOf(name))
const byName = (a, b) => rank(a) - rank(b) || a.length - b.length || (a < b ? -1 : 1)

const lines = [...byCode]
  .map(([code, names]) => [parseInt(code, 16), names.sort(byName)])
  .sort(([a, x], [b, y]) => rank(x[0]) - rank(y[0]) || classOf(x[0]).localeCompare(classOf(y[0])) || a - b)
  .map(([cp, names]) => `${cp.toString(16)} ${names.join(' ')}`)

writeFileSync(
  out,
  `# Nerd Fonts ${VERSION} glyph names (${meta.date.slice(0, 10)}), from glyphnames.json
# in https://github.com/ryanoasis/nerd-fonts (MIT). Each line: codepoint, then
# every name it has. Generated by scripts/nerd-glyphs.mjs; do not edit.
${lines.join('\n')}
`,
)
console.log(`${out}: ${Object.keys(glyphs).length} names, ${lines.length} glyphs`)
